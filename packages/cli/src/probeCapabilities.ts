for (const c of cases) {
  const sessionId = `probe-${Math.random().toString(36).slice(2, 8)}`;
  const turns = c.multiTurn ?? [c.say ?? ""];
  console.log("─".repeat(78));
  console.log(`【${c.group}】`);
  let last = null;
  for (const t of turns) {
    console.log(`  用户> ${t}`);
    last = await app.orchestrator.handleMessage(
      app.envelope({ channel: "app", text: t, sessionId }),
    );
    const first = last.reply.split("\n").filter((l) => l.trim())[0] ?? "(空)";
    console.log(`  Agent> ${first}`);
    if (last.promptFor?.kind && last.promptFor.kind !== "none") {
      console.log(`         [需要:${last.promptFor.kind}]`);
    }
    if (last.terminal) console.log(`         [终局:${last.terminal.kind}]`);
  }
}
console.log("─".repeat(78));
